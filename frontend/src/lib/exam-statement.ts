export type ExamStatementPresentation =
  | { kind: 'plain'; text: string }
  | {
      kind: 'formula' | 'equation' | 'system';
      prompt: string;
      mathLines: string[];
      trailingText: string;
    }
  | {
      kind: 'sequence';
      prompt: string;
      values: string[];
      trailingText: string;
    };

const SAFE_EXPRESSION = /^[\da-zA-Z\s.,+\-−×*/=()^√]+$/u;
const TRAILING_QUESTION = /\.\s*((?:Найдите|Определите|Укажите)\s+[a-zA-Z])\s*[.!?]?\s*$/iu;

/** Convert a deliberately small math-expression vocabulary into safe TeX. */
export function formatMathExpression(expression: string): string | null {
  const source = expression.trim().replace(/[.!?]+\s*$/u, '').trim();
  if (!source || !SAFE_EXPRESSION.test(source) || !/\d/u.test(source)) return null;

  const tex = source
    .replace(/\s+/gu, ' ')
    .replace(/×|\*/gu, ' \\times ')
    .replace(/(\d)\s*,\s*(\d)/gu, '$1{,}$2')
    .replace(/(\d)\.(\d)/gu, '$1{,}$2')
    .replace(/(\d)\s*\/\s*(\d)/gu, '\\frac{$1}{$2}')
    .replace(/([\da-zA-Z]+)\s*\^\s*(-?\d+)/gu, '$1^{$2}')
    .replace(/√\s*\(([^()]*)\)/gu, '\\sqrt{$1}')
    .replace(/√\s*([\da-zA-Z]+)/gu, '\\sqrt{$1}')
    .replace(/\+\s*-(?=\d)/gu, '+ -')
    .replace(/−/gu, '-');

  if (/[√^]/u.test(tex) || /\\frac/u.test(tex)) {
    // Every supported command above is generated by this function; source
    // input itself rejects backslashes and braces.
    if (/\\sqrt\{\s*\}/u.test(tex) || /\\frac\{[^}]*\}\{\s*\}/u.test(tex)) return null;
  }
  return tex;
}

export function parseExamStatement(statement: string): ExamStatementPresentation {
  const text = statement.trim();
  const colon = text.indexOf(':');
  if (colon < 0) return { kind: 'plain', text };

  const prompt = text.slice(0, colon).trim();
  const body = text.slice(colon + 1).trim();
  if (/^Найдите следующий член последовательности$/iu.test(prompt)) {
    const sequence = body.replace(/[.!?]+\s*$/u, '').split(',').map((value) => value.trim());
    if (sequence.length >= 3 && sequence.every((value) => /^-?\d+(?:[.,]\d+)?$/u.test(value))) {
      return { kind: 'sequence', prompt, values: sequence, trailingText: '' };
    }
  }

  const trailing = body.match(TRAILING_QUESTION);
  const formulaText = trailing ? body.slice(0, trailing.index).trim() : body;
  const rawLines = /^Решите систему уравнений$/iu.test(prompt)
    ? formulaText.split(';').map((line) => line.trim())
    : [formulaText];
  const mathLines = rawLines.map(formatMathExpression);
  if (!mathLines.length || mathLines.some((line) => line === null)) {
    return { kind: 'plain', text };
  }

  const kind = rawLines.length > 1
    ? 'system'
    : /^Решите уравнение$/iu.test(prompt)
      ? 'equation'
      : 'formula';
  return {
    kind,
    prompt,
    mathLines: mathLines as string[],
    trailingText: trailing?.[1] ? `${trailing[1]}.` : '',
  };
}
